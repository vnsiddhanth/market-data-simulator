// Price-time priority limit order book for a single instrument.
//
// Data structure
// --------------
//   bids_ : std::map<Price, PriceLevel, std::greater<>>   best bid = begin()
//   asks_ : std::map<Price, PriceLevel, std::less<>>      best ask = begin()
//   PriceLevel::queue : std::deque<QueueEntry>            FIFO time priority
//   orders_ : std::unordered_map<OrderId, Order>          O(1) id lookup
//
// Complexity (L = number of populated price levels, typically < 100):
//   best bid/ask         O(1)       map::begin()
//   add (new level)      O(log L)   red-black tree insert
//   add (existing level) O(log L)   find + deque::push_back (amortised O(1))
//   cancel               O(1) avg   hash lookup + lazy tombstone (see below)
//   match one fill       O(1) avg   deque::pop_front
//
// Lazy cancellation
// -----------------
// Erasing from the middle of a std::deque is O(n) and invalidates iterators,
// so a cancel does NOT touch the queue. It removes the order from `orders_`,
// fixes the level's aggregate quantity immediately (so depth snapshots are
// always exact) and bumps a tombstone counter. The matcher skips stale entries
// when they reach the front. A level is compacted when tombstones dominate,
// which bounds memory at O(2 * live orders) per level.
//
// Each queue entry carries the order's sequence number, so a stale entry is
// never confused with a later order that happens to reuse the same id.
#pragma once

#include <cstddef>
#include <cstdint>
#include <deque>
#include <functional>
#include <map>
#include <optional>
#include <unordered_map>
#include <vector>

#include "mds/common/event.hpp"
#include "mds/common/types.hpp"

namespace mds {

struct Order {
    OrderId id{0};
    Price price{0};
    Qty qty{0};  // remaining (open) quantity
    Side side{Side::Buy};
    Timestamp ts{0};
    std::uint64_t seq{0};  // book-assigned arrival sequence; disambiguates tombstones
};

struct Fill {
    OrderId maker_id{0};
    OrderId taker_id{0};
    Price price{0};  // always the maker's (resting) price
    Qty qty{0};
    Side aggressor{Side::Buy};
    Timestamp ts{0};
};

struct LevelView {
    Price price{0};
    Qty qty{0};
    std::uint32_t orders{0};
};

struct BookStats {
    std::uint64_t adds{0};
    std::uint64_t cancels{0};
    std::uint64_t modifies{0};
    std::uint64_t market_orders{0};
    std::uint64_t rejects{0};  // unknown id, zero qty, duplicate id ...
    std::uint64_t fills{0};
    Qty volume{0};
    std::uint64_t compactions{0};
};

enum class BookResult : std::uint8_t {
    Ok = 0,
    UnknownOrder,
    DuplicateOrder,
    InvalidQty,
    InvalidPrice,
};

class OrderBook {
public:
    struct QueueEntry {
        OrderId id;
        std::uint64_t seq;
    };

    struct PriceLevel {
        std::deque<QueueEntry> queue;
        Qty total_qty{0};
        std::uint32_t live{0};        // live orders at this level
        std::uint32_t tombstones{0};  // cancelled entries still physically queued
    };

    using BidMap = std::map<Price, PriceLevel, std::greater<>>;
    using AskMap = std::map<Price, PriceLevel, std::less<>>;

    explicit OrderBook(SymbolId symbol = 0, std::size_t expected_orders = 1 << 16);

    // ---- order entry -------------------------------------------------------
    // Fills generated by the call are appended to `fills`.

    // Limit order: crosses the opposite side as far as `price` allows, any
    // remainder rests at `price`.
    BookResult add_limit(OrderId id, Side side, Price price, Qty qty, Timestamp ts,
                         std::vector<Fill>& fills);

    // Market order: sweeps the opposite side, never rests. Returns filled qty.
    Qty execute_market(OrderId id, Side side, Qty qty, Timestamp ts, std::vector<Fill>& fills);

    BookResult cancel(OrderId id);

    // Quantity change. A decrease keeps time priority (exchange convention);
    // an increase moves the order to the back of its level's queue.
    BookResult modify(OrderId id, Qty new_qty, Timestamp ts);

    // Dispatch a MarketEvent to the matching entry point.
    BookResult apply(const MarketEvent& ev, std::vector<Fill>& fills);

    // ---- market data -------------------------------------------------------
    [[nodiscard]] std::optional<Price> best_bid() const noexcept;
    [[nodiscard]] std::optional<Price> best_ask() const noexcept;
    [[nodiscard]] std::optional<Price> mid_price_x2() const noexcept;  // bid + ask, exact
    [[nodiscard]] std::optional<double> mid_price() const noexcept;
    [[nodiscard]] std::optional<Price> spread() const noexcept;

    [[nodiscard]] Qty volume_at(Side side, Price price) const noexcept;
    [[nodiscard]] Qty best_bid_qty() const noexcept;
    [[nodiscard]] Qty best_ask_qty() const noexcept;

    // Top-N aggregated levels, best first.
    [[nodiscard]] std::vector<LevelView> depth(Side side, std::size_t levels) const;
    void depth_into(Side side, std::size_t levels, std::vector<LevelView>& out) const;

    // Order-book imbalance over the top `levels`: (B - A) / (B + A) in [-1, 1].
    [[nodiscard]] double imbalance(std::size_t levels = 5) const noexcept;

    // Volume-weighted price to fill `qty` against `side` (side = side being hit).
    [[nodiscard]] std::optional<double> sweep_vwap(Side side, Qty qty) const noexcept;

    [[nodiscard]] const Order* find(OrderId id) const noexcept;
    [[nodiscard]] std::size_t order_count() const noexcept { return orders_.size(); }
    [[nodiscard]] std::size_t level_count(Side side) const noexcept {
        return side == Side::Buy ? bids_.size() : asks_.size();
    }
    [[nodiscard]] bool empty() const noexcept { return orders_.empty(); }
    [[nodiscard]] const BookStats& stats() const noexcept { return stats_; }
    [[nodiscard]] SymbolId symbol() const noexcept { return symbol_; }
    [[nodiscard]] Timestamp last_update() const noexcept { return last_ts_; }
    // Sequence number the next resting order will receive. Orders with a
    // smaller `seq` arrived earlier; the backtester uses this to decide
    // whether a cancelled order was ahead of a simulated order in the queue.
    [[nodiscard]] std::uint64_t next_sequence() const noexcept { return next_seq_; }

    const BidMap& bids() const noexcept { return bids_; }
    const AskMap& asks() const noexcept { return asks_; }

    void clear();

    // Debug-only O(N) invariant check: level aggregates match live orders,
    // book is not crossed, every live order is reachable from its level.
    [[nodiscard]] bool validate() const;

private:
    template <class Levels>
    Qty match(Levels& opposite, Side aggressor, OrderId taker, Price limit, Qty qty,
              Timestamp ts, std::vector<Fill>& fills);

    template <class Levels>
    void rest(Levels& levels, Order&& order);

    template <class Levels>
    void remove_from_level(Levels& levels, const Order& order);

    static void maybe_compact(PriceLevel& level, const std::unordered_map<OrderId, Order>& live,
                              BookStats& stats);

    SymbolId symbol_;
    BidMap bids_;
    AskMap asks_;
    std::unordered_map<OrderId, Order> orders_;
    std::uint64_t next_seq_{1};
    Timestamp last_ts_{0};
    BookStats stats_;
};

}  // namespace mds
