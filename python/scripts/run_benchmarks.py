#!/usr/bin/env python3
"""Run the C++ benchmarks and write a Markdown results file.

    python python/scripts/run_benchmarks.py --build build --out docs/BENCHMARK_RESULTS.md

Captures machine info, runs ``bench_queue`` / ``bench_orderbook`` /
``mds_backtest`` and stores their raw output verbatim, so numbers quoted in
the README can always be traced back to a reproducible run.
"""
from __future__ import annotations

import argparse
import datetime as dt
import os
import platform
import subprocess
import sys


def find_exe(build: str, name: str) -> str:
    for cand in (os.path.join(build, name), os.path.join(build, "Release", name),
                 os.path.join(build, name + ".exe"), os.path.join(build, "Release", name + ".exe")):
        if os.path.isfile(cand):
            return cand
    raise FileNotFoundError(f"{name} not found under {build}; build the project first")


def run(cmd):
    print("$", " ".join(cmd), flush=True)
    res = subprocess.run(cmd, capture_output=True, text=True, check=True)
    print(res.stdout)
    return res.stdout


def main() -> int:
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("--build", default="build")
    ap.add_argument("--out", default="docs/BENCHMARK_RESULTS.md")
    ap.add_argument("--messages", default="20000000")
    ap.add_argument("--events", default="2000000")
    ap.add_argument("--reps", default="5")
    ap.add_argument("--pin", default="", help="e.g. 2,4 to pin producer/consumer")
    args = ap.parse_args()

    q = [find_exe(args.build, "bench_queue"), "--messages", args.messages,
         "--events", args.events, "--reps", args.reps]
    if args.pin:
        q += ["--pin", args.pin]
    sections = [
        ("Queue: lock-free SPSC vs mutex", run(q)),
        ("Order book", run([find_exe(args.build, "bench_orderbook"), "--events", args.events,
                            "--reps", args.reps])),
        ("Backtest: market maker", run([find_exe(args.build, "mds_backtest"), "--strategy", "mm",
                                        "--events", args.events])),
        ("Backtest: imbalance taker", run([find_exe(args.build, "mds_backtest"), "--strategy", "obi",
                                           "--events", args.events])),
    ]
    with open(args.out, "w") as f:
        f.write("# Benchmark results\n\n")
        f.write(f"- date: {dt.datetime.now().isoformat(timespec='seconds')}\n")
        f.write(f"- machine: {platform.platform()} / {platform.processor() or platform.machine()}"
                f" / {os.cpu_count()} logical CPUs\n")
        f.write(f"- python: {sys.version.split()[0]}\n\n")
        f.write("Generated by `python/scripts/run_benchmarks.py`; raw output below.\n\n")
        for title, body in sections:
            f.write(f"## {title}\n\n```text\n{body.rstrip()}\n```\n\n")
    print(f"wrote {args.out}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
